"""Generate the Supabase migrations that come from data/ (specs/003-sys-core research R1, R3).

  supabase/migrations/20261101000100_schema.sql     the 49 tables of data/schema/schema-*.sql, unchanged,
                                                    then every foreign key as ALTER TABLE … ADD CONSTRAINT
  supabase/migrations/20261101000300_grants_rls.sql grants, RLS on every table, policies (tools/rls_policies.py)

Usage: python3 tools/build_supabase.py [--check]
  --check  exit 1 when the files on disk differ from what would be written (nothing is written)
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rls_policies import POLICIES, DEFERRED, ANON_TABLES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = ROOT / 'data' / 'schema'
OUT = ROOT / 'supabase' / 'migrations'
SCHEMA_FILE = OUT / '20261101000100_schema.sql'
RLS_FILE = OUT / '20261101000300_grants_rls.sql'

TABLE_RE = re.compile(r'((?:--[^\n]*\n)*)CREATE TABLE (\w+) \(\n(.*?)\n\);', re.S)
FK_RE = re.compile(r'^CONSTRAINT (\w+) (FOREIGN KEY \([^)]*\) REFERENCES )(\w+)( \([^)]*\))$')


def read_tables():
    """[(module, comment, table, [body lines])] in data/schema file order."""
    tables = []
    for path in sorted(SCHEMA_DIR.glob('schema-*.sql')):
        module = path.stem[len('schema-'):]
        for comment, name, body in TABLE_RE.findall(path.read_text(encoding='utf-8')):
            tables.append((module, comment, name, body.split('\n')))
    return tables


def schema_sql(tables):
    out = ['-- Generated by tools/build_supabase.py from data/schema/schema-*.sql — do not edit by hand.',
           '-- Tables, columns, types, constraint names and CHECK expressions are copied unchanged (specs/003-sys-core R1).',
           '-- Foreign keys follow all tables because the modules reference each other in cycles (M0 <-> M3, M4 <-> M5).',
           '']
    fks = []
    for module, comment, name, lines in tables:
        kept = []
        for raw in lines:
            item = raw.strip().rstrip(',')
            match = FK_RE.match(item)
            if match:
                constraint, head, target, cols = match.groups()
                fks.append(f'ALTER TABLE public.{name} ADD CONSTRAINT {constraint} {head}public.{target}{cols};')
            else:
                kept.append(item)
        last_item = max(i for i, item in enumerate(kept) if not item.startswith('--'))
        body = []
        for i, item in enumerate(kept):
            comma = ',' if not item.startswith('--') and i < last_item else ''
            body.append(f'    {item}{comma}')
        out.append(f'{comment}CREATE TABLE public.{name} (\n' + '\n'.join(body) + '\n);\n')
    out.append('-- Foreign keys\n' + '\n'.join(fks) + '\n')
    return '\n'.join(out)


def policy_name(p):
    return p.get('name') or f"rls_{p['table']}_{p['op']}_{'_'.join(p['roles'])}"


def rls_sql(tables):
    by_table = {}
    for p in POLICIES:
        by_table.setdefault(p['table'], []).append(p)
    deferred = {}
    for table, op, actor, oq in DEFERRED:
        deferred.setdefault(table, []).append((op, actor, oq))

    names = [name for _, _, name, _ in tables]
    unknown = sorted({p['table'] for p in POLICIES} - set(names))
    if unknown:
        raise SystemExit(f'Policies for unknown tables: {unknown}')

    out = ['-- Generated by tools/build_supabase.py from tools/rls_policies.py — do not edit by hand.',
           '-- Grants are checked before RLS: everything is revoked, then each policy gets the grant it needs.',
           '-- No DELETE grant or policy exists (BR-005, M3 BR-008). The System actor uses the secret key (D2).',
           '-- Annotations read by tests/unit/rls-coverage.test.js:',
           '--   policy: <table> <op> <roles> | deferred: <table> <op> <Actor> OQ<n> (research open question n)',
           '']
    for name in names:
        policies = by_table.get(name, [])
        out.append(f'-- {name}')
        out.append(f'REVOKE ALL ON public.{name} FROM anon, authenticated;')
        out.append(f'ALTER TABLE public.{name} ENABLE ROW LEVEL SECURITY;')
        if name in ANON_TABLES:
            out.append(f'GRANT SELECT ON public.{name} TO anon;')
        ops = {p['op'] for p in policies}
        if 'select' in ops:
            out.append(f'GRANT SELECT ON public.{name} TO authenticated;')
        if 'insert' in ops:
            out.append(f'GRANT INSERT ON public.{name} TO authenticated;')
        for p in policies:
            if p['op'] == 'update':
                cols = p.get('columns')
                out.append(f"GRANT UPDATE ({', '.join(cols)}) ON public.{name} TO authenticated;" if cols
                           else f'GRANT UPDATE ON public.{name} TO authenticated;')
        for p in policies:
            to = 'anon, authenticated' if 'anon' in p['roles'] else 'authenticated'
            out.append(f"-- policy: {name} {p['op']} {','.join(p['roles'])}")
            head = f"CREATE POLICY {policy_name(p)} ON public.{name} FOR {p['op'].upper()} TO {to}"
            if p['op'] == 'select':
                out.append(f"{head}\n  USING ({p['using']});")
            elif p['op'] == 'insert':
                out.append(f"{head}\n  WITH CHECK ({p['check']});")
            else:
                out.append(f"{head}\n  USING ({p['using']})\n  WITH CHECK ({p.get('check', p['using'])});")
        for op, actor, oq in deferred.get(name, []):
            out.append(f'-- deferred: {name} {op} {actor} OQ{oq}')
        out.append('')
    return '\n'.join(out)


def main():
    tables = read_tables()
    if len(tables) != 49:
        raise SystemExit(f'Expected 49 tables in data/schema, found {len(tables)}')
    files = {SCHEMA_FILE: schema_sql(tables), RLS_FILE: rls_sql(tables)}
    if '--check' in sys.argv:
        stale = [p.name for p, text in files.items() if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            print('Out of date:', ', '.join(stale), '— run python3 tools/build_supabase.py')
            sys.exit(1)
        print('OK: Supabase migrations match data/schema and tools/rls_policies.py')
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding='utf-8')
        print(f'wrote {path.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
